/* Verify the familiar results view in an actual browser. No external test traffic. */
const assert=require('node:assert/strict');
const {readFile}=require('node:fs/promises');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  try {
    const page=await browser.newPage({viewport:{width:1360,height:1000}});
    await page.goto('http://127.0.0.1:8501');
    const next=page.getByRole('button',{name:'Siguiente →',exact:true});
    await next.click();
    await page.getByRole('button',{name:'Ver resultado →',exact:true}).click();
    const headline=page.getByRole('heading',{name:'🏠 Falta una referencia de velocidad',exact:true});
    await headline.waitFor();
    const numbers=page.getByText('Detalle y números',{exact:true}).last();
    await numbers.waitFor();
    assert.equal(await page.getByText('Uso estimado de descarga',{exact:true}).isVisible(),false);
    await headline.scrollIntoViewIfNeeded();
    await page.screenshot({path:'/tmp/smartnet-family-results.png'});
    await page.getByText('Dejar las descargas para después',{exact:true}).click();
    await page.getByText('Esta opción no cambia las actividades ni las bandas de tu escenario.',{exact:true}).waitFor();
    assert.equal(await page.getByText(/Matrices, bandas y funciones|Matriz de/).count(),0);
    await numbers.click();
    await page.getByText('Uso estimado de descarga',{exact:true}).waitFor({state:'visible'});
    await page.setViewportSize({width:390,height:844});
    await headline.scrollIntoViewIfNeeded();
    await page.screenshot({path:'/tmp/smartnet-family-mobile.png'});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    console.log('Family results: summary, missing data, collapsed numbers, no-effect scenario, mobile width passed');
    const slides=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    await slides.goto('http://127.0.0.1:8501');
    const slidesBack=slides.getByRole('button',{name:'← Atrás',exact:true});
    const stage=name=>slides.getByRole('heading',{name,exact:true});
    await stage('¿Con qué velocidad cuenta la casa?').waitFor();
    await slides.locator('iframe[src*="smartnet_speed"]').waitFor();
    assert.equal(await slides.locator('.st-key-page_equipment').isVisible(),false);
    assert.equal(await slides.locator('.st-key-page_result').isVisible(),false);
    await slides.getByRole('button',{name:'Siguiente pantalla →',exact:true}).click();
    await stage('¿Qué equipos usan la conexión?').waitFor();
    await slides.getByRole('button',{name:'? Banda',exact:true}).click();
    await slides.getByText(/Abre las propiedades de la red conectada/).waitFor();
    await slides.getByText(/iPhone u otros equipos/).waitFor();
    await slides.keyboard.press('Escape');
    const preset=slides.getByTestId('stSelectbox').filter({hasText:'Prueba un ejemplo o arma tu casa'});
    await preset.getByRole('combobox').click();
    await slides.getByRole('option',{name:'Wi-Fi saturado · Plan asimétrico 300/10 Mbps',exact:true}).click();
    await slides.getByText('Equipos en este escenario: 8.',{exact:true}).waitFor();
    const firstCount=slides.getByRole('spinbutton',{name:'Cantidad 1',exact:true});
    await firstCount.fill('3');
    await firstCount.press('Enter');
    await slides.getByText('Equipos en este escenario: 9.',{exact:true}).waitFor();
    await slides.getByRole('button',{name:'Siguiente · Ver resultado →',exact:true}).click();
    await stage('Resultado de la prueba').waitFor();
    assert.equal(await firstCount.isVisible(),false);
    await stage('Prueba una mejora').waitFor();
    const overview=slides.locator('.st-key-family_summary').last();
    await overview.getByRole('heading',{name:'El Wi-Fi se queda corto',exact:true}).waitFor();
    const illustration=overview.locator('.st-key-result_art img');
    await illustration.waitFor({state:'visible'});
    await illustration.evaluate(img=>img.decode());
    assert((await illustration.boundingBox()).height<=112);
    const details=slides.getByText('Detalle y números',{exact:true}).last();
    assert((await stage('Prueba una mejora').boundingBox()).y < (await details.boundingBox()).y);
    const metrics=slides.getByText('Uso estimado de descarga',{exact:true});
    assert.equal(await metrics.isVisible(),false);
    await slides.getByText('Dejar las descargas para después',{exact:true}).click();
    await slides.getByText('Todavía falta capacidad en 2,4 GHz.',{exact:true}).waitFor();
    await slides.locator('.st-key-improvements').getByText(/Prueba cambiar equipos de banda/).waitFor();
    const chart=slides.getByRole('img',{name:'Antes: 108.0% · Con la propuesta: 35.9%',exact:true});
    assert.equal(await chart.isVisible(),false);
    await details.click();
    await slides.getByText('9 equipos · 300 Mbps de descarga · 10 Mbps de subida',{exact:true}).waitFor();
    await chart.waitFor();
    await slides.getByText('Sale de la saturación',{exact:true}).waitFor();
    const downloadPromise=slides.waitForEvent('download');
    await slides.getByRole('button',{name:'Descargar resumen como imagen',exact:true}).click();
    const download=await downloadPromise;
    assert.equal(download.suggestedFilename(),'smartnet-resumen.png');
    const png=await readFile(await download.path());
    assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
    assert.equal(png.readUInt32BE(16),1040);
    assert(png.readUInt32BE(20)>500);
    await slidesBack.click();
    await stage('¿Qué equipos usan la conexión?').waitFor();
    assert.equal(await firstCount.inputValue(),'3');
    await slides.getByRole('button',{name:'Ver resultado →',exact:true}).click();
    await slides.getByRole('button',{name:'Volver a la primera pregunta',exact:true}).click();
    await stage('¿Con qué velocidad cuenta la casa?').waitFor();
    assert.equal(await slides.getByText('Ver o editar equipos',{exact:true}).count(),0);
    assert(await slides.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    console.log('Presentation: bottom navigation, result, PNG download, retained edits and mobile width passed');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
